"""OnTrack demo app, home page: pipeline, data quality and governance overview (owner: P1).

    streamlit run src/ontrack/app/main.py

Pages in src/ontrack/app/pages/ appear in the sidebar automatically:
  1_C360.py (P1) · 2_Ask.py (P2) · 3_Agent_Card.py (P3)
"""
import streamlit as st

from ontrack.app.common import TAGLINE, header, query, table_exists

header("Collections intelligence", "Team HOmiES · CIBC Collections Hackathon · synthetic Maple Bank data, snapshot 28 Sep 2026")
st.info(f"**{TAGLINE}**")

if not table_exists("gold", "c360_customer"):
    st.error("Gold tables not found. Run `python -m ontrack.l1_factory.bronze` then `python -m ontrack.l1_factory.build`.")
    st.stop()

# ---- Headline numbers ----
k = query("""
    SELECT (SELECT count(*) FROM gold.c360_customer) AS people,
           (SELECT count(*) FROM gold.customer_xref) AS source_keys,
           (SELECT count(*) FROM gold.c360_account) AS accounts,
           (SELECT count(*) FROM gold.case_360 WHERE outcome IS NULL) AS open_cases,
           (SELECT count(*) FROM gold.match_review_queue) AS review_queue
""").iloc[0]
c = st.columns(5)
c[0].metric("Golden customers", f"{k.people:,}", help="One golden_id per person across 5 source systems")
c[1].metric("Source keys linked", f"{k.source_keys:,}")
c[2].metric("Accounts", f"{k.accounts:,}")
c[3].metric("Open collections cases", f"{k.open_cases:,}")
c[4].metric("Matches awaiting a steward", f"{k.review_queue:,}", help="Grey-zone matches (0.80–0.95), never auto-merged")

st.divider()
left, right = st.columns(2)

with left:
    st.markdown("#### Identity resolution")
    val = query("SELECT * FROM silver.splink_validation") if table_exists("silver", "splink_validation") else None
    if val is not None and len(val):
        v = val.iloc[0]
        st.success(f"Probabilistic matching checked blind on **{int(v.holdout_keys):,}** keys with a known owner: "
                   f"**precision {v.precision:.2%}**, **recall {v.recall:.2%}**")
    st.dataframe(query("""SELECT match_method AS "How linked", count(*) AS keys,
                                 round(avg(match_confidence), 3) AS "avg confidence"
                          FROM gold.customer_xref GROUP BY 1 ORDER BY 2 DESC"""),
                 hide_index=True, width="stretch")

with right:
    st.markdown("#### Data contract `DC-COLL-C360-001`")
    if table_exists("gold", "_contract_results"):
        res = query("""SELECT rule_id AS rule, rule_name AS "check", observed, threshold,
                              CASE WHEN passed THEN '✅ pass' ELSE '❌ FAIL' END AS result
                       FROM gold._contract_results ORDER BY rule_id""")
        st.dataframe(res, hide_index=True, width="stretch")
    st.caption("Rules live in `contracts/c360_customer.yaml` and run on every build.")

st.divider()
st.markdown("#### Data quality issues found and handled")
st.dataframe(query("""SELECT issue, table_name AS "table", records_affected AS "records affected", handling AS "how handled"
                      FROM silver._dq_issues ORDER BY records_affected DESC"""),
             hide_index=True, width="stretch")
st.caption("Full report: `docs/data_quality_report.md` (generated by the pipeline, never edited by hand).")

st.divider()
st.markdown("#### Governance in every layer")
g = st.columns(4)
g[0].markdown("**No protected attributes**  \nBlocked from gold, features and decisions; used only to test fairness.")
g[1].markdown("**Human review**  \nStewards approve grey-zone matches; agents accept, edit or reject every recommendation.")
g[2].markdown("**Explained decisions**  \nEvery recommendation carries a plain-English reason.")
g[3].markdown("**Hardship first**  \nHardship signals route cases to a person, never to pressure.")
