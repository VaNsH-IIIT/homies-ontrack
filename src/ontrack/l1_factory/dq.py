"""Data quality report, generated from the pipeline's own logs (owner: P1).

    python -m ontrack.l1_factory.dq        -> docs/data_quality_report.md

Sources: bronze._load_log (row counts, schema drift), bronze._cast_failures (values that do not
fit the declared type), silver._dq_issues (issues found while cleaning), gold checks below.
"""
from datetime import datetime

from ontrack import config
from ontrack.db import connect

GOLD_CHECKS = [
    ("golden_id unique in gold.c360_customer",
     "SELECT count(*) - count(DISTINCT golden_id) FROM gold.c360_customer",
     "Must be 0 (contract rule Q1)"),
    ("Collections cases without a golden_id (orphans)",
     "SELECT count(*) FROM gold.case_360 WHERE golden_id IS NULL",
     "Quarantined from decisioning; investigated (contract rule Q3)"),
    ("Contacts without a golden_id",
     "SELECT count(*) FROM gold.contact_timeline WHERE golden_id IS NULL",
     "Kept in the timeline; excluded from customer-level features"),
    ("Accounts linked only by tier-2 rules (name + DOB + postal/phone)",
     "SELECT count(*) FROM gold.customer_xref WHERE match_method LIKE 'name_dob_%'",
     "Accepted at 0.97 confidence; sampled for steward review"),
    ("Links refused by the conflict guard (would merge people with different dates of birth)",
     "SELECT count(*) FROM silver.identity_refused",
     "Not merged; logged for steward review"),
    ("Golden ids holding records with different dates of birth (possible wrong merges)",
     "SELECT count(*) FROM (SELECT x.golden_id FROM gold.customer_xref x JOIN silver.crm c ON x.source_system = 'crm' AND c.crm_customer_id = x.source_key GROUP BY 1 HAVING count(DISTINCT c.dob) > 1)",
     "Only possible via CRM's own duplicate flag; sampled for steward review"),
    ("Source keys left unlinked (singleton clusters)",
     "SELECT count(*) FROM gold.customer_xref x JOIN (SELECT golden_id FROM gold.customer_xref GROUP BY 1 HAVING count(*) = 1) s USING (golden_id)",
     "Phase 2: probabilistic matching (Splink); until then treated as separate customers"),
]


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join("" if v is None else (f"{v:,}" if isinstance(v, int) else str(v)) for v in r) + " |")
    return "\n".join(out)


def main() -> None:
    con = connect(read_only=True)
    lines = [
        "# Data quality report",
        "",
        f"_Generated by `python -m ontrack.l1_factory.dq` on {datetime.now():%Y-%m-%d %H:%M}. Do not edit by hand._",
        "",
        "Every number below is computed by the pipeline. Issues are listed with how many records they affect and how we handle them.",
        "",
        "## 1. Load checks (bronze)",
        "",
    ]
    loads = con.execute("""SELECT table_name, kind, rows, expected_rows,
                                  CASE WHEN rows = expected_rows THEN 'ok' ELSE 'MISMATCH' END,
                                  array_to_string(extra_cols, ', '), array_to_string(missing_cols, ', ')
                           FROM bronze._load_log ORDER BY table_name""").fetchall()
    lines += [md_table(["Table", "Kind", "Rows", "Expected", "Count check", "Columns not in schema (drift)",
                        "Schema columns missing"], loads), ""]

    lines += ["## 2. Values that do not fit their declared type", ""]
    casts = con.execute("""SELECT table_name, column_name, target_type, failed_count, sample_value
                           FROM bronze._cast_failures ORDER BY failed_count DESC""").fetchall()
    lines += [md_table(["Table", "Column", "Declared type", "Records affected", "Example value"], casts)
              if casts else "None found.", "",
              "Handling: the raw value is kept in the source file; the typed column is null; downstream steps treat it as missing.", ""]

    lines += ["## 3. Issues found while cleaning (silver)", ""]
    issues = con.execute("SELECT issue, table_name, records_affected, handling FROM silver._dq_issues").fetchall()
    lines += [md_table(["Issue", "Table", "Records affected", "How handled"], issues), ""]

    lines += ["## 4. Golden record checks (gold)", ""]
    gold_rows = [(name, con.execute(sql).fetchone()[0], handling) for name, sql, handling in GOLD_CHECKS]
    lines += [md_table(["Check", "Records", "Rule / handling"], gold_rows), ""]

    results = con.execute("SELECT rule_id, rule_name, observed, threshold, CASE WHEN passed THEN 'pass' ELSE 'FAIL' END, "
                          "on_failure FROM gold._contract_results ORDER BY rule_id").fetchall()
    lines += ["### Data contract quality rules (`contracts/c360_customer.yaml`)", "",
              md_table(["Rule", "Check", "Observed", "Threshold", "Result", "On failure"], results), ""]

    val = con.execute("SELECT holdout_keys, auto_linked, precision, recall FROM silver.splink_validation").fetchone()
    queue = con.execute("SELECT count(*) FROM gold.match_review_queue").fetchone()[0]
    lines += ["### Probabilistic matching (Splink, tier 3): accuracy on known links", "",
              f"Matched blind: {val[0]:,} source keys whose owner is already known from tier-1 case-to-account bridges.", "",
              md_table(["Holdout keys", "Auto-linked (p >= 0.95)", "Precision", "Recall"], [val]), "",
              f"Grey-zone matches (0.80 <= p < 0.95) sent to the data-steward queue `gold.match_review_queue`: **{queue:,}** (not merged).", ""]

    xref = con.execute("""SELECT match_method, count(*), round(avg(match_confidence), 3)
                          FROM gold.customer_xref GROUP BY 1 ORDER BY 2 DESC""").fetchall()
    lines += ["### Identity resolution: how each source key was linked", "",
              md_table(["Method", "Keys", "Avg confidence"], xref), ""]

    out = config.REPO_ROOT / "docs" / "data_quality_report.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    con.close()


if __name__ == "__main__":
    main()
